package dev.slimevr.bones

/**
 * The standard body parts a bone in a [BoneRegistry] may represent. Not a wire type: SolarXR
 * only ever carries a bone's numeric id and string key, so nothing on the wire needs this.
 */
enum class BodyPart(val value: UByte) {
	NONE(0u),
	HEAD(1u),
	NECK(2u),
	UPPER_CHEST(3u),
	LOWER_CHEST(4u),
	UPPER_WAIST(5u),
	LOWER_WAIST(6u),
	HIP(7u),
	LEFT_UPPER_LEG(8u),
	RIGHT_UPPER_LEG(9u),
	LEFT_LOWER_LEG(10u),
	RIGHT_LOWER_LEG(11u),
	LEFT_FOOT(12u),
	RIGHT_FOOT(13u),
	LEFT_UPPER_ARM(14u),
	RIGHT_UPPER_ARM(15u),
	LEFT_LOWER_ARM(16u),
	RIGHT_LOWER_ARM(17u),
	LEFT_HAND(18u),
	RIGHT_HAND(19u),
	LEFT_SHOULDER(20u),
	RIGHT_SHOULDER(21u),
	LEFT_THUMB_METACARPAL(22u),
	LEFT_THUMB_PROXIMAL(23u),
	LEFT_THUMB_DISTAL(24u),
	LEFT_INDEX_PROXIMAL(25u),
	LEFT_INDEX_INTERMEDIATE(26u),
	LEFT_INDEX_DISTAL(27u),
	LEFT_MIDDLE_PROXIMAL(28u),
	LEFT_MIDDLE_INTERMEDIATE(29u),
	LEFT_MIDDLE_DISTAL(30u),
	LEFT_RING_PROXIMAL(31u),
	LEFT_RING_INTERMEDIATE(32u),
	LEFT_RING_DISTAL(33u),
	LEFT_LITTLE_PROXIMAL(34u),
	LEFT_LITTLE_INTERMEDIATE(35u),
	LEFT_LITTLE_DISTAL(36u),
	RIGHT_THUMB_METACARPAL(37u),
	RIGHT_THUMB_PROXIMAL(38u),
	RIGHT_THUMB_DISTAL(39u),
	RIGHT_INDEX_PROXIMAL(40u),
	RIGHT_INDEX_INTERMEDIATE(41u),
	RIGHT_INDEX_DISTAL(42u),
	RIGHT_MIDDLE_PROXIMAL(43u),
	RIGHT_MIDDLE_INTERMEDIATE(44u),
	RIGHT_MIDDLE_DISTAL(45u),
	RIGHT_RING_PROXIMAL(46u),
	RIGHT_RING_INTERMEDIATE(47u),
	RIGHT_RING_DISTAL(48u),
	RIGHT_LITTLE_PROXIMAL(49u),
	RIGHT_LITTLE_INTERMEDIATE(50u),
	RIGHT_LITTLE_DISTAL(51u),
	LEFT_BIG_TOE(52u),
	LEFT_INDEX_TOE(53u),
	LEFT_MIDDLE_TOE(54u),
	LEFT_RING_TOE(55u),
	LEFT_LITTLE_TOE(56u),
	RIGHT_BIG_TOE(57u),
	RIGHT_INDEX_TOE(58u),
	RIGHT_MIDDLE_TOE(59u),
	RIGHT_RING_TOE(60u),
	RIGHT_LITTLE_TOE(61u),
	;

	companion object {
		fun fromValue(value: UByte): BodyPart? = entries.firstOrNull { it.value == value }
	}
}
